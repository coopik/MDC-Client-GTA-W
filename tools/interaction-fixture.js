'use strict'

const assert = require('assert/strict')
const fs = require('fs')
const path = require('path')

async function verifyInteractions({shell,guest,until,delay,win,output,webContents}) {
  const key = async (contents,keyCode,modifiers=[]) => {
    contents.focus()
    contents.sendInputEvent({type:'keyDown',keyCode,modifiers})
    contents.sendInputEvent({type:'keyUp',keyCode,modifiers})
    await delay(120)
  }
  await shell(`setTheme('p1');dialogRoots.slice().forEach(closeDialog);wv.loadURL('https://mdc.gta.world/profile')`)
  await until(async()=>!(await guest()).isLoading(),'shortcut fixture ready')
  await shell(`showKeys()`)
  assert.equal(await shell(`document.querySelectorAll('.key-set[data-key^="nav:"]').length`),await shell('navItems.length'),'every discovered navigation button is bindable')
  await shell(`document.querySelector('.key-set[data-key="nav:/"]').click()`)
  await key(win.webContents,'F1')
  assert.equal(await shell(`comboFor('nav:/')`),'F1','shortcut capture assigns a navigation key')
  assert.equal(await shell(`comboFor('keyhelp')`),'','taking a default binding disables the old action')
  assert.equal(await shell(`document.querySelector('.menu-item[data-action="keyhelp"] .accel').textContent`),'','Help menu clears a stolen or disabled default key')
  assert.equal(await shell(`document.querySelectorAll('.navkey').length`),1,'only a bound navigation button has a badge')
  assert.equal(await shell(`document.querySelector('.navkey').textContent`),'F1','navigation badge shows the current key')
  fs.writeFileSync(path.join(output,'navigation-key-badge.png'),(await win.webContents.capturePage()).toPNG())
  await shell(`closeDialog()`)
  await shell(`window.fixtureSoundCalls=[];window.fixturePlaySound=playSound;playSound=name=>fixtureSoundCalls.push(name);void 0`)
  await key(await guest(),'F1')
  await until(async()=>(await guest()).getURL()==='https://mdc.gta.world/'&&!(await guest()).isLoading(),'navigation key works inside MDC')
  assert.deepEqual(await shell('fixtureSoundCalls'), ['nav'], 'bound navbar navigation emits nav without a synthetic click sound')
  assert.equal(await shell('SOUND_FILES.nav'), 'sounds/nav.mp3', 'navigation resolves the requested audio asset')
  await shell(`playSound=fixturePlaySound;void 0`)
  await shell(`showKeys();document.querySelector('.key-clear[data-key="nav:/"]').click()`)
  assert.equal(await shell(`document.querySelectorAll('.navkey').length`),0,'clearing a binding removes its badge')
  await shell(`document.querySelector('.key-set[data-key="nav:/"]').click()`)
  await key(win.webContents,'g',['control','alt'])
  assert.equal(await shell(`comboFor('nav:/')`),'Ctrl+Alt+G','modifier combinations are captured')
  await shell(`closeDialog();wv.loadURL('https://mdc.gta.world/profile')`)
  await until(async()=>!(await guest()).isLoading()&&(await guest()).getURL().endsWith('/profile'),'modifier navigation ready')
  await key(await guest(),'g',['control','alt'])
  await until(async()=>(await guest()).getURL()==='https://mdc.gta.world/','same modifier binding works in embedded page')
  await shell(`showKeys();document.getElementById('key-reset').click();closeDialog()`)
  assert.equal(await shell(`document.querySelector('.menu-item[data-action="keyhelp"] .accel').textContent`),'F1','Help menu restores the default label after reset')
  await shell(`showKeys();document.querySelector('.key-clear[data-key="keyhelp"]').click()`)
  assert.equal(await shell(`document.querySelector('.menu-item[data-action="keyhelp"] .accel').textContent`),'','Help menu clears an explicitly unbound shortcut')
  await shell(`document.querySelector('.key-set[data-key="keyhelp"]').click()`)
  await key(win.webContents,'F6')
  assert.equal(await shell(`document.querySelector('.menu-item[data-action="keyhelp"] .accel').textContent`),'F6','Help menu follows remapped combinations')
  await shell(`document.getElementById('key-reset').click();closeDialog();fixtureSoundCalls=[];playSound=name=>fixtureSoundCalls.push(name);void 0`)
  await key(win.webContents,'3',['control'])
  assert.deepEqual(await shell('fixtureSoundCalls'), ['nav'], 'law-page navigation uses the navigation tone')
  await shell(`playSound=fixturePlaySound;void 0`)
  assert.equal(await shell('activeTab'),'depa','DEPA has a default Ctrl+3 binding')
  await until(()=>shell(`laws.depa.el.getAttribute('data-loaded')==='1'`),'DEPA starts loading')
  const depa=webContents.fromId(await shell('laws.depa.el.getWebContentsId()'))
  await until(async()=>!depa.isLoading()&&await depa.executeJavaScript("!!document.getElementById('mdt-penal-skin')"),'DEPA preload ready')
  await shell('sendKeys()')
  await delay(100)
  await key(depa,'4',['control'])
  await until(()=>shell("activeTab==='shaft'"),'law shortcuts work from another law page')
  await shell(`showKeys();document.querySelector('.key-set[data-key="tabdepa"]').click()`)
  await key(win.webContents,'F7')
  await shell(`closeDialog();showTab('mdc')`)
  await key(await guest(),'F7')
  assert.equal(await shell('activeTab'),'depa','law bindings can be changed')
  await shell(`showKeys();document.getElementById('key-reset').click();closeDialog();showTab('mdc');actions.zoomreset()`)
  await key(win.webContents,'=',['control'])
  assert.equal(await shell('Math.round(Math.pow(1.2,zoom)*100)'),110,'chrome zoom increases by 10%')
  await key(await guest(),'+',['control','shift'])
  assert.equal(await shell('Math.round(Math.pow(1.2,zoom)*100)'),120,'page shifted plus increases by 10%')
  const rail=await shell('quickWidth')
  await shell(`document.querySelector('.quickresize').focus()`)
  await key(win.webContents,'-',['control'])
  assert.equal(await shell('quickWidth'),rail,'Ctrl+Minus on the rail changes page zoom only')
  assert.equal(await shell('Math.round(Math.pow(1.2,zoom)*100)'),110,'chrome and page zoom share one state')
  await shell(`openPage('https://mdc.gta.world/record/zoom-test')`)
  await until(async()=>!(await guest()).isLoading(),'new page zoom ready')
  assert.ok(Math.abs((await guest()).getZoomFactor()-1.1)<.01,'new pages inherit global zoom')
  for(const percent of [50,80,100,150,200]) {
    await shell(`setZoom(Math.log(${percent}/100)/Math.log(1.2))`)
    await delay(150)
    const dimensions=await shell(`(()=>{const box=document.querySelector('.content').getBoundingClientRect(),view=wv.getBoundingClientRect();return {width:Math.abs(box.width-view.width),height:Math.abs(box.height-view.height)}})()`)
    assert.ok(dimensions.width<1&&dimensions.height<1,'webview fills the content at '+percent+'% '+JSON.stringify(dimensions))
    assert.ok(Math.abs((await guest()).getZoomFactor()-percent/100)<.01,'actual page factor at '+percent+'%')
    assert.equal(win.webContents.getZoomFactor(),1,'native shell zoom remains fixed')
    assert.ok(Math.abs(depa.getZoomFactor()-percent/100)<.01,'law pages use the same saved factor')
  }
  await key(await guest(),'0',['control'])
  assert.equal(await shell('zoom'),0,'Ctrl+0 resets shared zoom')
  await shell(`wv.loadURL('https://mdc.gta.world/workspace')`)
  await until(async()=>!(await guest()).isLoading()&&await (await guest()).executeJavaScript('!!window.jQuery'),'wheel fixture ready')
  const g=await guest()
  const read=(code)=>g.executeJavaScript(code,true)
  await read(`(()=>{const link=document.createElement('link');link.rel='stylesheet';link.href='/site-vendor/custom.css';document.head.appendChild(link);const space=document.createElement('div');space.style.height='1800px';document.querySelector('.content').appendChild(space);document.querySelector('#floatOne .modal-title').textContent='View Arrest Report';document.querySelector('#floatOne .modal-body').innerHTML=Array.from({length:100},(_,i)=>'<p>Read-only report paragraph '+i+'</p>').join('')})()`)
  for(const theme of ['p1','aero','aerolapd','aerodark']) {
    await shell(`setTheme('${theme}')`)
    await read(`$('#floatOne').modal('show')`)
    await delay(250)
    const start=await read(`(()=>{const r=document.querySelector('#floatOne .modal-header').getBoundingClientRect();return {x:Math.round(r.x+65),y:Math.round(r.y+r.height/2)}})()`)
    g.sendInputEvent({type:'mouseDown',...start,button:'left',clickCount:1})
    g.sendInputEvent({type:'mouseMove',x:start.x+40,y:start.y+40,movementX:40,movementY:40})
    g.sendInputEvent({type:'mouseUp',x:start.x+40,y:start.y+40,button:'left',clickCount:1})
    await delay(100)
    await read(`document.querySelector('#floatOne .modal-body').scrollTop=0;window.scrollTo(0,100)`)
    const pageTop=await read('document.scrollingElement.scrollTop')
    const point=await read(`(()=>{const r=document.querySelector('#floatOne .modal-body').getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+50)}})()`)
    g.sendInputEvent({type:'mouseMove',...point})
    g.sendInputEvent({type:'mouseWheel',...point,deltaX:0,deltaY:-160,canScroll:true})
    await delay(180)
    assert.ok(await read(`document.querySelector('#floatOne .modal-body').scrollTop`)>0,theme+': wheel scrolls the focused report contents')
    assert.equal(await read('document.scrollingElement.scrollTop'),pageTop,theme+': report wheel does not move the background page')
    await read(`(()=>{const body=document.querySelector('#floatOne .modal-body');body.scrollTop=body.scrollHeight})()`)
    g.sendInputEvent({type:'mouseWheel',...point,deltaX:0,deltaY:-160,canScroll:true})
    await delay(100)
    assert.equal(await read('document.scrollingElement.scrollTop'),pageTop,theme+': report boundaries do not leak wheel scrolling to the page')
    await read(`$('#floatOne').modal('hide')`)
    await delay(200)
  }
  console.log('PASS navigation badges, shortcut capture/conflicts/clearing, law bindings, shared zoom and report wheel routing')
  return 5
}

module.exports={verifyInteractions}
